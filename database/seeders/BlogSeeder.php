## چرا پیامک پترن؟

پیامک پترن روی خطوط خدماتی ارسال می‌شود و حتی برای کاربرانی که تبلیغات را در سامانهٔ «۱۰۸۸» مسدود کرده‌اند هم تحویل داده می‌شود. الگوی پیام از قبل ثبت و تأیید می‌شود و شما فقط مقادیر متغیر را می‌فرستید.

مثال الگو:

```
کد ورود شما به {brand}: {code}
این کد تا {minutes} دقیقه معتبر است.
```

## قواعد طراحی کد یک‌بارمصرف

- **طول کد:** ۵ یا ۶ رقم. کمتر از ۵ رقم امنیت کافی ندارد.
- **انقضا:** بین ۲ تا ۵ دقیقه. کد منقضی‌شده باید از پایگاه داده حذف یا بی‌اثر شود.
- **یک‌بار مصرف واقعی:** پس از استفادهٔ موفق، کد باطل شود.
- **عدم فاش شدن در لاگ:** کد را در لاگ سرور یا ابزارهای رصد ذخیره نکنید.

