| هزینه‌تراشی رقیب | محدودسازی بر اساس IP و شناسهٔ دستگاه علاوه بر شماره |

## نمونهٔ ارسال از طریق API

```php
use Illuminate\Support\Facades\Http;

$code = (string) random_int(10000, 99999);

cache()->put("otp:{$mobile}", $code, now()->addMinutes(3));

Http::withToken(config('services.irnoti.key'))
    ->post('https://api.irnoti.com/v1/pattern/send', [
        'sender' => '3000XXXX',
        'recipient' => $mobile,
        'pattern_code' => 'otp_login',
        'variables' => ['code' => $code, 'minutes' => 3],
    ]);
```

هنگام تأیید، مقدار واردشده را با مقدار کش مقایسه کنید و در صورت تطابق، بلافاصله کلید کش را حذف کنید.

